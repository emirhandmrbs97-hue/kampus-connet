type TranslationKey = keyof typeof translations.tr;

type LanguageContextValue = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => Promise<void>;
  t: (key: TranslationKey) => string;
};

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>('tr');

  useEffect(() => {
    let active = true;
    void AsyncStorage.getItem(LANGUAGE_KEY)
      .then((saved) => {
        if (!active) return;
        if (saved === 'tr' || saved === 'en' || saved === 'de') setLanguageState(saved);
      })
      .catch((error: unknown) => {
        console.error('Dil tercihi yüklenemedi:', error);
      });
    return () => {
      active = false;
    };
  }, []);

  const setLanguage = useCallback(async (next: AppLanguage) => {
    await AsyncStorage.setItem(LANGUAGE_KEY, next);
    setLanguageState(next);
  }, []);

  const t = useCallback((key: TranslationKey) => translations[language][key], [language]);
  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside <LanguageProvider>');
  return context;
}
