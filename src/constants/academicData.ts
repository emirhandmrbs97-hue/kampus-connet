export const STANDARD_DEPARTMENTS: readonly string[] = ACADEMIC_DEPARTMENT_GROUPS.flatMap(
  (group) => group.data,
);

function normalizeAcademicName(value: string): string {
  return value
    .trim()
    .toLocaleLowerCase('tr-TR')
    .replace(/ı/g, 'i')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, ' ');
}

function findCanonicalName(value: string, options: readonly string[]): string | null {
  const normalizedValue = normalizeAcademicName(value);
  if (!normalizedValue) return null;
  return options.find((option) => normalizeAcademicName(option) === normalizedValue) ?? null;
}

export function validateTurkishUniversityName(value: string): {
  valid: boolean;
  canonicalName: string | null;
  suggestions: string[];
} {
  const canonicalName = findCanonicalName(value, TURKISH_UNIVERSITY_NAMES);
  const normalizedValue = normalizeAcademicName(value);
  const suggestions = normalizedValue
    ? TURKISH_UNIVERSITY_NAMES.filter((name) => normalizeAcademicName(name).includes(normalizedValue)).slice(0, 6)
    : [];
  return { valid: canonicalName !== null, canonicalName, suggestions };
}

export function validateDepartmentName(value: string): {
  valid: boolean;
  canonicalName: string | null;
  suggestions: string[];
} {
  const canonicalName = findCanonicalName(value, STANDARD_DEPARTMENTS);
  const normalizedValue = normalizeAcademicName(value);
  const suggestions = normalizedValue
    ? STANDARD_DEPARTMENTS.filter((name) => normalizeAcademicName(name).includes(normalizedValue)).slice(0, 6)
    : [];
  return { valid: canonicalName !== null, canonicalName, suggestions };
}
